//! The checks on the specification registry that read the tree (#907).
//!
//! `Registry::validate` covers what the file alone can prove. This adds what it
//! cannot: that every module and test a record cites exists, that every
//! `spec-ref:` comment in the workspace names a record, and that the generated
//! part of `docs/user-docs/api/specifications.mdx` is current. Regenerate that
//! with `just gen-specs` (`ROLTER_TEST_UPDATE_SPEC_DOCS=1`), then run
//! `just fmt-docs`, which aligns the tables; the comparison ignores alignment.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use rolter_core::spec_registry::{self, Category, Registry, Spec};

const PAGE: &str = "docs/user-docs/api/specifications.mdx";
const BEGIN: &str = "{/* spec-registry:begin — generated by `just gen-specs`, do not edit */}";
const END: &str = "{/* spec-registry:end */}";

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn registry() -> Registry {
    spec_registry::parse(spec_registry::SOURCE).expect("the embedded registry parses")
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|err| panic!("{}: {err}", path.display()))
}

#[test]
fn every_cited_module_and_test_exists() {
    let registry = registry();
    let mut missing = Vec::new();
    let tests = registry
        .specs
        .iter()
        .flat_map(|spec| spec.tests.iter())
        .chain(registry.providers.iter().flat_map(|p| p.tests.iter()));
    for test in tests {
        let (file, name) = match test.split_once("::") {
            Some((file, name)) => (file, Some(name)),
            None => (test.as_str(), None),
        };
        let path = root().join(file);
        if !path.is_file() {
            missing.push(format!("test file {file}"));
            continue;
        }
        if let Some(name) = name {
            let source = read(&path);
            if !source.contains(&format!("fn {name}(")) {
                missing.push(format!("test {test}"));
            }
        }
    }
    for module in registry.specs.iter().flat_map(|spec| spec.modules.iter()) {
        if !root().join(module).is_file() {
            missing.push(format!("module {module}"));
        }
    }
    assert!(
        missing.is_empty(),
        "the registry cites what is not there: {missing:#?}"
    );
}

#[test]
fn legacy_sse_acceptance_claim_covers_empty_2xx_replies() {
    let registry = registry();
    let spec = registry
        .specs
        .iter()
        .find(|spec| spec.id == "mcp-transport")
        .expect("the MCP transport record exists");
    assert!(
        spec.omissions
            .iter()
            .any(|line| line.contains("answers 2xx with no reply")),
        "the published claim names only the old 202 case: {:?}",
        spec.omissions
    );
    assert!(
        spec.tests.iter().any(|test| test
            .ends_with("a_legacy_sse_empty_2xx_is_accepted_with_its_reply_on_the_stream")),
        "the record does not cite the empty-2xx regression test"
    );
}

/// Every `.rs` file under `crates/*/src` and `crates/*/tests`.
fn workspace_sources() -> Vec<PathBuf> {
    fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                walk(&path, out);
            } else if path.extension().is_some_and(|e| e == "rs") {
                out.push(path);
            }
        }
    }
    let mut files = Vec::new();
    for krate in std::fs::read_dir(root().join("crates")).expect("crates/ is readable") {
        let krate = krate.expect("readable entry").path();
        walk(&krate.join("src"), &mut files);
        walk(&krate.join("tests"), &mut files);
    }
    files.sort();
    files
}

/// The ids named by `spec-ref:` comments in `text`: a comma-separated list of
/// ids after the marker, up to the end of the line.
fn spec_refs(text: &str) -> Vec<String> {
    let mut ids = Vec::new();
    for line in text.lines() {
        let Some((_, rest)) = line.split_once("spec-ref:") else {
            continue;
        };
        for id in rest.split(',') {
            let id: String = id
                .trim()
                .chars()
                .take_while(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || *c == '-')
                .collect();
            ids.push(id);
        }
    }
    ids
}

#[test]
fn spec_ref_comments_name_real_records() {
    let registry = registry();
    let known: BTreeSet<&str> = registry.specs.iter().map(|s| s.id.as_str()).collect();
    let mut unknown = Vec::new();
    let mut seen = 0;
    for file in workspace_sources() {
        // this file names the marker in prose and in a fixture
        if file.ends_with("tests/spec_registry.rs") {
            continue;
        }
        for id in spec_refs(&read(&file)) {
            seen += 1;
            if !known.contains(id.as_str()) {
                unknown.push(format!("{}: '{id}'", file.display()));
            }
        }
    }
    assert!(unknown.is_empty(), "spec-ref names no record: {unknown:#?}");
    // the comments are the trail from code to the registry; a sweep that
    // removed them all would otherwise pass
    assert!(seen >= 20, "only {seen} spec-ref comments in the workspace");
}

#[test]
fn the_ref_parser_reads_lists_and_stops_at_prose() {
    assert_eq!(
        spec_refs("// spec-ref: sse, openai-chat-completions\n//! spec-ref: rfc3339 (timestamps)"),
        ["sse", "openai-chat-completions", "rfc3339"]
    );
    assert_eq!(spec_refs("// spec-ref: Not-An-Id"), [""]);
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

fn code_list(items: &[String]) -> String {
    if items.is_empty() {
        return "—".into();
    }
    items
        .iter()
        .map(|item| format!("`{item}`"))
        .collect::<Vec<_>>()
        .join("<br />")
}

fn version_of(spec: &Spec) -> String {
    match (&spec.version, &spec.pinned) {
        (Some(version), Some(pinned)) => format!("{version} (`{}`)", &pinned[..12]),
        (Some(version), None) => version.clone(),
        (None, _) => format!("{} (no revision)", spec.contract.as_str()),
    }
}

const CATEGORIES: &[(Category, &str)] = &[
    (Category::AiApi, "AI APIs"),
    (Category::Translation, "Translations"),
    (Category::WireFormat, "Wire formats"),
    (Category::Transport, "Transport"),
    (Category::Identity, "Identity"),
    (Category::Telemetry, "Telemetry"),
    (Category::ApiDescription, "API description"),
];

/// The generated part of the user-docs page.
fn render(registry: &Registry) -> String {
    let mut out = String::new();
    for (category, heading) in CATEGORIES {
        let specs: Vec<&Spec> = registry
            .specs
            .iter()
            .filter(|spec| spec.category == *category)
            .collect();
        if specs.is_empty() {
            continue;
        }
        let _ = writeln!(out, "### {heading}\n");
        out.push_str("| Specification | Revision | Conformance | Reviewed | Endpoints |\n");
        out.push_str("| --- | --- | --- | --- | --- |\n");
        for spec in &specs {
            let endpoints: Vec<String> = spec
                .gateway_endpoints
                .iter()
                .chain(&spec.control_endpoints)
                .cloned()
                .collect();
            let _ = writeln!(
                out,
                "| [{}]({}) (`{}`) | {} | {} | {} | {} |",
                cell(&spec.title),
                spec.url,
                spec.id,
                cell(&version_of(spec)),
                spec.conformance.as_str(),
                spec.reviewed_at,
                code_list(&endpoints)
            );
        }
        out.push('\n');
        for spec in specs {
            let _ = writeln!(out, "#### {}\n", spec.title);
            let _ = writeln!(
                out,
                "`{}` · {} · [primary source]({})\n",
                spec.id, spec.authority, spec.url
            );
            for (label, items) in [
                ("Supported", &spec.supported),
                ("Omitted", &spec.omissions),
                ("Deviations", &spec.deviations),
            ] {
                for item in items {
                    let _ = writeln!(out, "- **{label}:** {item}");
                }
            }
            if let Some(notes) = &spec.notes {
                let _ = writeln!(out, "- **Note:** {notes}");
            }
            let _ = writeln!(out, "- **Evidence:** {}", code_list(&spec.tests));
            out.push('\n');
        }
    }

    out.push_str("### Provider kinds\n\n");
    out.push_str(
        "| Kind | Documentation | Auth | Primary path | Example `api_base` | Conformance | Reviewed | Evidence |\n",
    );
    out.push_str("| --- | --- | --- | --- | --- | --- | --- | --- |\n");
    for provider in &registry.providers {
        let kind = serde_json::to_value(provider.kind)
            .ok()
            .and_then(|v| v.as_str().map(str::to_string))
            .unwrap_or_default();
        let mut docs = format!("[{}]({})", cell(&provider.authority), provider.url);
        if let Some(notes) = &provider.notes {
            let _ = write!(docs, " — {}", cell(notes));
        }
        let _ = writeln!(
            out,
            "| `{kind}` | {docs} | `{}` | `{}` | {} | {} | {} | {} |",
            provider.auth.header(),
            provider.primary_path,
            provider
                .base
                .as_ref()
                .map_or("—".to_string(), |base| format!("`{base}`")),
            provider.conformance.as_str(),
            provider.reviewed_at,
            code_list(&provider.tests)
        );
    }
    out
}

/// Ignore the column padding `just fmt-docs` adds to a table.
fn normalise(text: &str) -> String {
    text.lines()
        .map(|line| {
            let line = line.trim_end();
            if !line.starts_with('|') {
                return line.to_string();
            }
            line.split('|')
                .map(|cell| {
                    let cell = cell.trim();
                    if !cell.is_empty() && cell.bytes().all(|b| b == b'-') {
                        "---"
                    } else {
                        cell
                    }
                })
                .collect::<Vec<_>>()
                .join("|")
        })
        .collect::<Vec<_>>()
        .join("\n")
        .trim()
        .to_string()
}

#[test]
fn the_generated_docs_are_current() {
    let path = root().join(PAGE);
    let page = read(&path);
    let (head, rest) = page
        .split_once(BEGIN)
        .unwrap_or_else(|| panic!("{PAGE} lost its `{BEGIN}` marker"));
    let (current, tail) = rest
        .split_once(END)
        .unwrap_or_else(|| panic!("{PAGE} lost its `{END}` marker"));
    let generated = render(&registry());
    if std::env::var_os("ROLTER_TEST_UPDATE_SPEC_DOCS").is_some() {
        let updated = format!("{head}{BEGIN}\n\n{generated}\n{END}{tail}");
        std::fs::write(&path, updated).expect("the docs page is writable");
        return;
    }
    assert_eq!(
        normalise(current),
        normalise(&generated),
        "{PAGE} is stale: run `just gen-specs` and then `just fmt-docs`"
    );
}

#[test]
fn normalising_ignores_only_table_padding() {
    assert_eq!(
        normalise("| a   | b |\n| --- | ----- |\ntext  "),
        normalise("| a | b |\n| --- | --- |\ntext")
    );
    assert_ne!(normalise("| a | b |"), normalise("| a | c |"));
}
